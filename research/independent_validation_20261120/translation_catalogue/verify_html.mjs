import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
const base=path.dirname(fileURLToPath(import.meta.url));
const output=process.argv[2];if(!output)throw new Error('Supply screenshot output directory');
const released=process.argv[3]==='released';
const catalogueFile=released?path.join(output,'catalogue.html'):path.join(base,'results/catalogue.html');
const pairsFile=released?path.join(output,'../ivc-proto-reconstruction/word_pairs.html'):path.join(base,'../proto_reconstruction/results/word_pairs.html');
const associationsFile=released?path.join(output,'../ivc-context-associations/associations.html'):path.join(base,'../context_associations/results/associations.html');
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(pathToFileURL(catalogueFile).href);
 if(!(await page.locator('#count').textContent()).includes('9,252'))throw new Error('Complete catalogue did not load');
 const headers=await page.locator('thead th').allTextContents();
 if(headers[2]!=='Found at')throw new Error('Findspot must be beside the translation');
 await page.locator('#example').click();
 const text=await page.locator('#body').textContent();
 for(const expected of ['M-1954','Mohenjo-daro','DKE','Trench E-','-1090/1980','-9.0 ft'])if(!text.includes(expected))throw new Error('Missing actual findspot: '+expected);
 await page.screenshot({path:path.join(output,'findspot_example.png'),fullPage:true});
 await page.locator('#q').fill('');await page.locator('#word').selectOption('220');
 const count=await page.locator('#count').textContent();
 if(count.startsWith('0 records'))throw new Error('Meaning/sign filter returned no fish-sign records');
 await page.goto(pathToFileURL(catalogueFile).href+'?sign=892');
 if(await page.locator('#word').inputValue()!=='892')throw new Error('Word-pair occurrence link did not filter the catalogue');
 await page.goto(pathToFileURL(pairsFile).href);
 await page.locator('#q').fill('bow → sell');
 const entry=page.locator('details.entry:visible').first();
 await entry.locator('summary').click();
 if(!(await entry.textContent()).includes('Found at'))throw new Error('Word-pair examples do not show actual locations');
 if(await entry.locator('tbody tr').count()===0)throw new Error('No findspot example rows');
 await page.screenshot({path:path.join(output,'word_pair_findspots.png'),fullPage:false});
 await entry.locator('a').click();
 await page.waitForLoadState('load');
 await page.waitForFunction(()=>document.getElementById('word')?.value==='892');
 if(await page.locator('#word').inputValue()!=='892')throw new Error('Word-pair occurrence link is broken');
 await page.goto(pathToFileURL(catalogueFile).href+'?sign=007,017&city=Mohenjo-daro');
 if(await page.locator('#word').inputValue()!=='007,017')throw new Error('Allograph group link is broken');
 await page.goto(pathToFileURL(associationsFile).href);
 await page.locator('#q').fill('tax/levy');await page.locator('#axis').selectOption('material');
 const copper=page.locator('#body tr').filter({hasText:'material: Copper'}).first();
 const copperText=await copper.textContent();
 if(!copperText.includes('29/38')||!copperText.includes('148/3662'))throw new Error('Incorrect tax/copper counts in rendered table');
 await page.screenshot({path:path.join(output,'associations_preview.png'),fullPage:false});
 await copper.locator('a').click();await page.waitForLoadState('load');
 await page.waitForFunction(()=>document.getElementById('word')?.value==='845'&&document.getElementById('material')?.value==='Copper');
 if(await page.locator('#material').inputValue()!=='Copper')throw new Error('Material/findspot link did not apply its context');
 await page.goto(pathToFileURL(associationsFile).href);
 await page.locator('#q').fill('tax/tribute');await page.locator('#axis').selectOption('excavation_area');
 await page.locator('#body tr').filter({hasText:'Harappa | area FTrench I'}).first().locator('a').click();
 await page.waitForLoadState('load');
 await page.waitForFunction(()=>document.getElementById('context-filter')?.textContent.includes('FTrench I'));
 if(!/Excavation area: FTrench I(?:;|$)/.test(await page.locator('#body .findspot').first().textContent()))throw new Error('Trench link did not select the actual recorded area');
 await page.goto(pathToFileURL(associationsFile).href);
 await page.locator('#q').fill('new-cloth');await page.locator('#axis').selectOption('recorded_layer');
 await page.locator('#body tr').filter({hasText:'phase=II; period=Late'}).first().locator('a').click();
 await page.waitForLoadState('load');
 await page.waitForFunction(()=>document.getElementById('context-filter')?.textContent.includes('phase recorded: II'));
 if(!(await page.locator('#body .strata').first().textContent()).includes('Phase / stratum: II; Period: Late'))throw new Error('Layer link did not select the recorded phase and period');
 await page.goto(pathToFileURL(path.join(path.dirname(associationsFile),'copper845.html')).href);
 if(await page.locator('table').first().locator('tr').count()!==30)throw new Error('The copper specimen table must contain all 29 objects plus its header');
 if(!(await page.locator('table').first().textContent()).includes('M-585'))throw new Error('Copper table missing specimen M-585');
 await page.screenshot({path:path.join(output,'copper845_specimens.png'),fullPage:false});
 if(errors.length)throw new Error(errors.join('\n'));
 console.log(JSON.stringify({records:9252,findspotExample:'M-1954: Mohenjo-daro, DKE, Trench E-, -1090/1980, -9.0 ft',meaningFilter:count,urlSignFilter:true,browserErrors:errors.length}));
}finally{await browser.close()}
